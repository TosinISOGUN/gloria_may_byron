/*
 * Builds the evidence images for the authenticity page from the screenshots Gloria shared.
 *   node scripts/build-evidence.mjs
 * Each screenshot is cropped to the part that matters (the phone's status bar, black margins and buttons are
 * left out), and the two halves of one email are joined into a single image. Nothing is retouched or re-typed:
 * the pixels are Gloria's. Output: public/evidence/*.webp and src/data/evidence.generated.ts (sizes).
 */
import fs from "node:fs";
import path from "node:path";

import sharp from "sharp";

const SRC = "assets-source/GLORIA FILES/FILES/SCREENSHOTS SHARED BY GLORIA";
const OUT = "public/evidence";
fs.mkdirSync(OUT, { recursive: true });

const shot = (name) => path.join(SRC, name);
// [left, top, width, height] in the original screenshot, measured from the files.
const jobs = [
  {
    id: "certificate",
    parts: [{ file: "embedded fingerprint.jpg", box: [0, 0, 1080, 748] }],
  },
  {
    // The opening of one email: what the platforms flag, and that the distributor passed the files.
    id: "emailPlatformsA",
    parts: [{ file: "photo_3_2026-11-12_16-42-06.jpg", box: [16, 268, 706, 1004] }],
  },
  {
    // The sign-off of the same email. The part between the two is about selling music on another site, and is left out.
    id: "emailPlatformsB",
    parts: [{ file: "photo_4_2026-11-12_16-42-06.jpg", box: [16, 1133, 706, 125] }],
  },
  {
    id: "emailTidal",
    parts: [{ file: "photo_6_2026-11-12_16-42-06.jpg", box: [16, 284, 706, 1032] }],
  },
  {
    id: "emailMixea",
    parts: [{ file: "photo_9_2026-11-12_16-42-06.jpg", box: [16, 270, 706, 1058] }],
  },
];

const manifest = {};
for (const job of jobs) {
  const pieces = [];
  for (const part of job.parts) {
    const [left, top, width, height] = part.box;
    pieces.push(await sharp(shot(part.file)).extract({ left, top, width, height }).toBuffer());
  }
  const meta = await Promise.all(pieces.map((b) => sharp(b).metadata()));
  const width = Math.max(...meta.map((m) => m.width));
  const height = meta.reduce((s, m) => s + m.height, 0);
  let y = 0;
  const base = sharp({ create: { width, height, channels: 3, background: "#fbfbfd" } });
  const composed = await base
    .composite(pieces.map((input, i) => {
      const top = y;
      y += meta[i].height;
      return { input, left: 0, top };
    }))
    .png()
    .toBuffer();
  const file = `${job.id}.webp`;
  await sharp(composed).webp({ quality: 90 }).toFile(path.join(OUT, file));
  manifest[job.id] = { src: `/evidence/${file}`, width, height };
  console.log(job.id, `${width}x${height}`);
}

fs.writeFileSync(
  "src/data/evidence.generated.ts",
  `// Generated by scripts/build-evidence.mjs. Do not edit.\nexport const evidenceImages = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type EvidenceId = keyof typeof evidenceImages;\n`,
);
console.log("evidence images written");
