/*
 * Prepares the social cards for the website's contact page.
 *   node scripts/build-share-cards.mjs     (once, needs Chrome: renders social-cards/<lang>/*.png)
 *   node scripts/build-share-assets.mjs    (this: web files for the site)
 *
 * Per language, per design (motto, lead) and size (feed 4:5, story 9:16):
 *   public/share/<lang>/<design>-<size>.jpg   the full 1080-wide picture people save and post
 *   public/share/<lang>/<design>-<size>.webp  a lighter copy shown on the page
 *   public/share/<lang>/thumb.webp            a small motto card for the language row
 * and src/data/share-cards.generated.ts with each language's name and caption words, taken from the same
 * message files the cards were made from. Nothing is retouched: the pictures are the rendered cards.
 */
import fs from "node:fs";
import path from "node:path";

import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const SRC = path.join(root, "social-cards");
const OUT = path.join(root, "public/share");
const { locales } = await import("../src/i18n/locales.ts");
const en = (await import("../src/i18n/messages/en.ts")).en;

const designs = ["motto", "lead"];
const sizes = { feed: { w: 720, h: 900 }, story: { w: 540, h: 960 } };

const manifest = {};
for (const loc of locales) {
  const dir = path.join(OUT, loc.code);
  fs.mkdirSync(dir, { recursive: true });
  const m = loc.code === "en" ? en : (await import(`../src/i18n/messages/${loc.code}.ts`)).default;
  const pick = (fn, fallback) => {
    try {
      return fn(m) ?? fallback;
    } catch {
      return fallback;
    }
  };
  for (const design of designs) {
    for (const [size, box] of Object.entries(sizes)) {
      const src = path.join(SRC, loc.code, `gloria-${design}-${size}.png`);
      if (!fs.existsSync(src)) throw new Error(`missing ${src}: run scripts/build-share-cards.mjs first`);
      await sharp(src).jpeg({ quality: 90, chromaSubsampling: "4:4:4", mozjpeg: true }).toFile(path.join(dir, `${design}-${size}.jpg`));
      await sharp(src).resize(box.w, box.h).webp({ quality: 82 }).toFile(path.join(dir, `${design}-${size}.webp`));
    }
  }
  await sharp(path.join(SRC, loc.code, "gloria-motto-feed.png")).resize(240, 300).webp({ quality: 78 }).toFile(path.join(dir, "thumb.webp"));
  manifest[loc.code] = {
    native: loc.native,
    english: loc.english,
    lang: loc.hreflang,
    dir: loc.dir,
    motto: pick((x) => x.brand.motto, en.brand.motto),
    intro: pick((x) => x.home.hero.lead, en.home.hero.lead),
    path: loc.code === "en" ? "/" : `/${loc.code}/`,
  };
  console.log(loc.code);
}

fs.writeFileSync(
  path.join(root, "src/data/share-cards.generated.ts"),
  `// Generated by scripts/build-share-assets.mjs. Do not edit.\nexport const shareCards = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type ShareCardLocale = keyof typeof shareCards;\n`,
);
const bytes = (d) => fs.readdirSync(d, { recursive: true }).reduce((s, f) => { const p = path.join(d, f); return s + (fs.statSync(p).isFile() ? fs.statSync(p).size : 0); }, 0);
console.log(`public/share written, ${(bytes(OUT) / 1048576).toFixed(1)} MB`);
