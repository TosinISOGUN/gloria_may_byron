const ytIds = fs
  .readdirSync(YT)
  .filter((f) => f.endsWith(".jpg"))
  .map((f) => f.replace(/\.jpg$/, ""));

fs.mkdirSync(OUT, { recursive: true });
const manifest = {};

async function responsive(id, file, widths, { alpha = false } = {}) {
  const meta = await sharp(file).metadata();
  const w = meta.width;
  const h = meta.height;
  const sizes = [
    ...new Set([...widths.filter((x) => x < w), w <= widths.at(-1) ? w : widths.at(-1)]),
  ].sort((a, b) => a - b);
  for (const size of sizes) {
    const img = sharp(file).resize({ width: size, withoutEnlargement: true });
    const base = path.join(OUT, `${id}-${size}`);
    if (fs.existsSync(`${base}.avif`) && fs.existsSync(`${base}.webp`)) continue;
    await img
      .clone()
      .avif({ quality: alpha ? 62 : 52, effort: 4 })
      .toFile(`${base}.avif`);
    await img
      .clone()
      .webp({ quality: alpha ? 82 : 78 })
      .toFile(`${base}.webp`);
  }
  manifest[id] = { w, h, sizes };
}

for (const [id, f] of Object.entries(photos)) await responsive(id, path.join(SRC, f), photoWidths);

for (let n = 1; n <= 23; n++) {
  const nn = String(n).padStart(2, "0");
  await responsive(`release${nn}`, path.join(SRC, `${nn}.png`), releaseWidths, { alpha: true });
}

for (const id of ytIds) await responsive(`yt-${id}`, path.join(YT, `${id}.jpg`), thumbWidths);

for (const [id, f] of Object.entries(marks)) {
  const file = path.join(SRC, f);
  const meta = await sharp(file).metadata();
  const size = Math.min(meta.width, 480);
  await sharp(file)
    .resize({ width: size, withoutEnlargement: true })
    .webp({ quality: 90, alphaQuality: 95 })
    .toFile(path.join(OUT, `${id}-${size}.webp`));
  manifest[id] = { w: meta.width, h: meta.height, sizes: [size], webpOnly: true };
}

const body = `// Generated by scripts/build-images.mjs. Do not edit by hand.\nexport type ImageMeta = { w: number; h: number; sizes: number[]; webpOnly?: boolean };\n\nexport const images = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageMeta>;\n\nexport type ImageId = keyof typeof images;\n`;
fs.writeFileSync(path.join(root, "src/data/images.generated.ts"), body);
